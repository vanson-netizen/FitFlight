const assert = require('assert')
const fs = require('fs')
const path = require('path')
const crypto = require('crypto')
const { IMAGE_ENTRIES, PLACEHOLDER_IMAGE, resourceImage, homeImage } = require('../constants/community-resource-images')
const { imageErrorHandler } = require('../pages/community-shared/image-fallback')
const { loadResourceList } = require('../services/community-resource-service')
const release = require('../cloudfunctions/campusResourceAdmin/buaa-resources-student-v1.json')
const audit = JSON.parse(fs.readFileSync('docs/community-image-audit.json', 'utf8').replace(/^\ufeff/, ''))

async function run() {
  const originals = JSON.stringify(release)
  const ids = new Set(Object.values(release.collections).flat().map((record) => record._id))
  assert.strictEqual(new Set(IMAGE_ENTRIES.flatMap((entry) => entry.ids)).size, IMAGE_ENTRIES.flatMap((entry) => entry.ids).length)
  assert.strictEqual(new Set(['sport', 'food', 'forum'].map(homeImage)).size, 3)
  for (const entry of IMAGE_ENTRIES) {
    assert.ok(fs.existsSync('.' + entry.src), entry.src)
    assert.ok(entry.ids.every((id) => ids.has(id)), 'unknown stable ID')
    const item = audit.find((item) => `/assets/community/${item.file}` === entry.src)
    assert.ok(item)
    assert.strictEqual(item.width / item.height, 16 / 9)
    assert.ok(item.width >= (entry.home ? 750 : 640) && item.width <= 960)
    assert.strictEqual(item.format, 'JPEG')
    const bytes = fs.readFileSync('.' + entry.src)
    assert.strictEqual(bytes.length, item.bytes)
    assert.strictEqual(bytes.readUInt16BE(0), 0xffd8)
    assert.strictEqual(bytes.readUInt16BE(bytes.length - 2), 0xffd9)
    assert.ok(bytes.length < 120 * 1024)
    const original = fs.readFileSync(path.join('C:/FitFlight/社区图片', item.source))
    assert.strictEqual(crypto.createHash('sha256').update(original).digest('hex').toUpperCase(), item.sourceSha256)
  }
  assert.ok(fs.existsSync('.' + PLACEHOLDER_IMAGE))
  assert.strictEqual(resourceImage({}), PLACEHOLDER_IMAGE)
  assert.strictEqual(resourceImage({ resourceId: 'unknown', name: '蔓味轻食' }), PLACEHOLDER_IMAGE, 'no fuzzy name matching')
  const halls = release.collections.campus_dining_halls.map((hall) => ({ ...hall, category: 'dining_hall', resourceId: hall.diningHallId }))
  const food = release.collections.campus_food_options.map((food) => ({ ...food, resourceId: food.foodOptionId, name: food.dishName }))
  const result = await loadResourceList('food', 'dining_hall', { records: halls })
  assert.strictEqual(result.items.length, 6)
  const heyi = result.items.find((hall) => hall.name === '合一餐厅')
  assert.strictEqual(heyi.sourceDiningHallIds.length, 2)
  assert.ok(heyi.displayImage.endsWith('dining-xueyuan-hall-e9ba17ae34.jpg'))
  assert.strictEqual(new Set(heyi.sourceDiningHallIds.map((resourceId) => resourceImage({ resourceId }))).size, 1)
  const meals = await loadResourceList('food', 'healthy_light_meal', { records: [...halls, ...food] })
  const merchant = meals.items.find((item) => item.cardType === 'merchant')
  const heyiFood = meals.items.find((item) => item.resourceId === 'food-xueyuan-option-bd51c94c2f')
  assert.strictEqual(heyiFood.diningHallId, 'dining-xueyuan-hall-e9ba17ae34')
  assert.strictEqual(heyiFood.name, '减脂餐')
  assert.strictEqual(heyiFood.category, 'healthy_light_meal')
  assert.strictEqual(heyiFood.displayImage, '/assets/community/food-xueyuan-option-bd51c94c2f.jpg')
  assert.notStrictEqual(heyiFood.displayImage, PLACEHOLDER_IMAGE)
  assert.strictEqual(merchant.name, '蔓味轻食')
  assert.ok(merchant.displayImage.endsWith('merchant-xueyuan-road-manwei-light-meal.jpg'))
  assert.notStrictEqual(merchant.displayImage, merchant.foodItems[0].displayImage)
  const badmintonIds = ['venue-xueyuan-ball-sports-f36627c68a', 'venue-xueyuan-ball-sports-b69bcc106d']
  const badminton = await loadResourceList('sport', 'ball_sports', { records: release.collections.campus_venues.map((venue) => ({ ...venue, resourceId: venue.venueId })) })
  assert.strictEqual(badminton.items.filter((item) => badmintonIds.includes(item.resourceId)).length, 2)
  assert.strictEqual(new Set(badmintonIds.map((resourceId) => resourceImage({ resourceId }))).size, 2)
  const longList = Array.from({ length: 40 }, (_, i) => ({ resourceId: `missing-${i}`, category: 'gym', name: '测试资源' }))
  assert.strictEqual((await loadResourceList('sport', 'gym', { records: longList })).items.length, 40)
  assert.strictEqual(JSON.stringify(release), originals)

  const failureLogs = []
  const originalWarn = console.warn
  console.warn = (...args) => failureLogs.push(args)
  for (const [collection, idField, imageField] of [['resources', 'resourceId', 'displayImage'], ['entries', 'id', 'backgroundImage']]) {
    const page = { data: { [collection]: [{ [idField]: 'test', [imageField]: '/bad-path.jpg', name: 'keep-text' }] }, setData(update) { Object.assign(this.data, update) } }
    const handle = imageErrorHandler(collection, idField, imageField).bind(page)
    handle({ currentTarget: { dataset: { id: 'test', src: '/stale-image.jpg' } } })
    assert.strictEqual(page.data[collection][0][imageField], '/bad-path.jpg')
    handle({ currentTarget: { dataset: { id: 'test', src: '/bad-path.jpg' } } })
    assert.strictEqual(page.data[collection][0][imageField], PLACEHOLDER_IMAGE)
    assert.strictEqual(page.data[collection][0].name, 'keep-text')
    handle({ currentTarget: { dataset: { id: 'test', src: PLACEHOLDER_IMAGE } } })
    assert.strictEqual(page.data[collection][0].imageHidden, true)
    const before = page.data[collection]
    handle({ currentTarget: { dataset: { id: 'test', src: PLACEHOLDER_IMAGE } } })
    assert.strictEqual(page.data[collection], before, 'placeholder failure must not loop')
  }
  console.warn = originalWarn
  assert.strictEqual(failureLogs.length, 4)
  assert.ok(failureLogs.some(([, detail]) => detail.id === 'test' && detail.path === '/bad-path.jpg'))
  for (const type of ['community', 'community-sport', 'community-food']) {
    const source = fs.readFileSync(`pages/${type}/${type}.wxml`, 'utf8')
    assert.ok(source.includes('binderror="onImageError"'))
    assert.ok(source.includes('mode="aspectFill"'))
    assert.ok(!source.includes('/assets/community/'), 'paths belong in centralized config')
  }
  const style = fs.readFileSync('pages/community-resource/community-resource.wxss', 'utf8')
  assert.ok(style.includes('padding-top: 56.25%'))
  const homeStyle = fs.readFileSync('pages/community/community.wxss', 'utf8')
  assert.ok(homeStyle.includes('min-height: 200rpx'))
  assert.ok(homeStyle.includes('gap: 18rpx'))
  console.log(`Community image mapping, original hashes, ${audit.length} JPEG assets, merchant/badminton identity, safe fallback and ratio checks passed.`)
}
run().catch((error) => { console.error(error); process.exitCode = 1 })
