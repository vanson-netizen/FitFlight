const assert = require('assert')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const { isSafeCacheKey, SAFE_CACHE_EXACT_KEYS, SAFE_CACHE_KEY_PREFIXES } = require('../constants/local-storage')
const { listSafeCacheKeys } = require('../utils/local-cache')
const { APP_VERSION } = require('../constants/app-info')

assert.strictEqual(isSafeCacheKey('fitflight:journal-draft:v1:notebook:draft_1'), true)
assert.strictEqual(isSafeCacheKey('fitflight.userProfile'), false)
assert.strictEqual(isSafeCacheKey('body_profiles'), false)
assert.deepStrictEqual(listSafeCacheKeys(['fitflight.userProfile', 'fitflight:journal-draft:v1:n:e']), ['fitflight:journal-draft:v1:n:e'])
assert.strictEqual(SAFE_CACHE_EXACT_KEYS.length, 0)
assert.deepStrictEqual(SAFE_CACHE_KEY_PREFIXES, ['fitflight:journal-draft:v1:'])
assert.ok(/^\d+\.\d+\.\d+$/.test(APP_VERSION))

const app = JSON.parse(fs.readFileSync(path.join(root, 'app.json'), 'utf8'))
;['pages/settings/settings', 'pages/data-usage/data-usage', 'pages/about/about'].forEach((route) => {
  assert.ok(app.pages.includes(route), `missing route ${route}`)
  ;['js', 'json', 'wxml', 'wxss'].forEach((ext) => assert.ok(fs.existsSync(path.join(root, `${route}.${ext}`))))
  const pageConfig = JSON.parse(fs.readFileSync(path.join(root, `${route}.json`), 'utf8'))
  assert.strictEqual(pageConfig.usingComponents['navigation-bar'], '/components/navigation-bar/navigation-bar')
  const pageWxml = fs.readFileSync(path.join(root, `${route}.wxml`), 'utf8')
  assert.ok(pageWxml.includes('back="{{true}}"'), `${route} must expose a back button`)
})

const settingsWxml = fs.readFileSync(path.join(root, 'pages/settings/settings.wxml'), 'utf8')
assert.ok(settingsWxml.includes('bindtap="openPermissionSettings"'))
assert.ok(settingsWxml.includes('bindtap="confirmClearCache"'))
const cacheSource = fs.readFileSync(path.join(root, 'utils/local-cache.js'), 'utf8')
assert.ok(!cacheSource.includes('clearStorage'))
const indexWxml = fs.readFileSync(path.join(root, 'pages/index/index.wxml'), 'utf8')
assert.ok(indexWxml.includes('bindtap="openSettings"'))
const indexWxss = fs.readFileSync(path.join(root, 'pages/index/index.wxss'), 'utf8')
assert.ok(indexWxss.includes('.menu-card-single { min-height: 104rpx; display: flex; }'))
assert.ok(indexWxss.includes('.menu-item { width: 100%; min-height: 104rpx; display: flex; align-items: center;'))

console.log('Settings tests passed')
